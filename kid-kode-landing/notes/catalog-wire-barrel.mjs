#!/usr/bin/env node
// Regenerate src/lib/prism/animatable/primitives/index.ts from whatever primitive
// files exist on disk (orchestrator-owned shared file — written ONCE after each
// parallel fan-out so agents never contend on it). Deterministic + idempotent.
//
// For each primitives/<name>.ts (except index.ts), the expected export symbol is
// camelCase(name) + 'Primitive'. We verify the file actually exports it, then
// rebuild the barrel: imports (ordered by category, then name) + ALL_PRIMITIVES.
//
// Usage: node notes/catalog-wire-barrel.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const primDir = join(repoRoot, 'src/lib/prism/animatable/primitives');

const CATEGORY_ORDER = [
  'transform', 'fade', 'scroll', 'pointer', 'text',
  'wave', 'displacement', 'mask', 'blur', 'shimmer',
  'glass', 'caustics', 'volumetric', 'smoke', 'particles',
];

const camel = (kebab) => kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const exportNameOf = (name) => camel(name) + 'Primitive';

// DEFERRED — primitives kept on disk (valid + unit-tested) but intentionally NOT
// registered in the shippable catalog. Excluded from the barrel so they never reach
// the picker / a user / the AI builder until revived.
//   pointer-loupe: true optical magnification needs a framebuffer/render-target
//     magnification pass (sample a wider region into the lens disc); the synchronous
//     per-node createNode contract has no post-pass, so a geometry-warp loupe over the
//     featureless dark card body reads as a dark occluding bead and the harness's
//     orbiting-pointer pin lands it inconsistently over content vs gap. Advocate
//     BLOCKED across 3 fix-rounds (PRIMITIVES-EXPANSION W3). Revisit with a RT pass.
const DEFERRED = new Set(['pointer-loupe']);

const files = readdirSync(primDir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .filter((name) => !DEFERRED.has(name));

const entries = [];
const problems = [];
for (const name of files) {
  const exportName = exportNameOf(name);
  const src = readFileSync(join(primDir, `${name}.ts`), 'utf8');
  if (!new RegExp(`export\\s+const\\s+${exportName}\\b`).test(src)) {
    // try to discover the actual export
    const m = src.match(/export\s+const\s+(\w+Primitive)\s*:/);
    problems.push({ name, expected: exportName, found: m ? m[1] : '(none)' });
    if (m) { entries.push({ name, exportName: m[1], category: catOf(src) }); }
    continue;
  }
  entries.push({ name, exportName, category: catOf(src) });
}

function catOf(src) {
  const m = src.match(/category:\s*'([a-z-]+)'/);
  return m ? m[1] : 'zzz';
}

entries.sort((a, b) => {
  const ca = CATEGORY_ORDER.indexOf(a.category);
  const cb = CATEGORY_ORDER.indexOf(b.category);
  if (ca !== cb) return (ca < 0 ? 99 : ca) - (cb < 0 ? 99 : cb);
  return a.name.localeCompare(b.name);
});

const importLines = entries.map((e) => `import { ${e.exportName} } from './${e.name}';`).join('\n');
const arrayLines = entries.map((e) => `  ${e.exportName},`).join('\n');

const out = `// Catalog manifest — imports every primitive definition and registers it.
// Importing this module populates the Animatable registry (side-effect on first
// import). AUTO-GENERATED by notes/catalog-wire-barrel.mjs after each parallel
// fan-out — ordered by category then name. Do not hand-edit; re-run the wirer.

import { registerPrimitive } from '../registry';
import type { PrimitiveDefinition } from '../contract';

${importLines}

export const ALL_PRIMITIVES: PrimitiveDefinition[] = [
${arrayLines}
];

let registered = false;
export function registerAllPrimitives(): void {
  if (registered) return;
  for (const def of ALL_PRIMITIVES) registerPrimitive(def);
  registered = true;
}

registerAllPrimitives();
`;

writeFileSync(join(primDir, 'index.ts'), out);
console.log(`[wire-barrel] wrote index.ts with ${entries.length} primitives`);
console.log(`[wire-barrel] by category: ${JSON.stringify(
  entries.reduce((m, e) => ((m[e.category] = (m[e.category] || 0) + 1), m), {}),
)}`);
if (problems.length) {
  console.log(`[wire-barrel] EXPORT-NAME MISMATCHES (${problems.length}):`);
  for (const p of problems) console.log(`  ${p.name}: expected ${p.expected}, found ${p.found}`);
  process.exitCode = 3;
}
