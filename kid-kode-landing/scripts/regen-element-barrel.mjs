// Regenerate the prebuilt-element catalog barrel (catalog/index.ts).
//
// The 2 SEED elements use NAMED exports + explicit registerElement (registerAllElements).
// Every NEW Phase-2 element self-registers on import (calls registerElement at module
// scope) + default-exports — so the barrel just needs a side-effect import per new file.
// This script scans the catalog dir and emits a deterministic, alphabetized barrel.

import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.resolve('src/lib/editor/elements/catalog');
const SEEDS = {
  'carousel-photoreal-ring': 'carouselPhotorealRing',
  'hero-photoreal-monolith': 'heroPhotorealMonolith',
};

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .sort();

const seedFiles = files.filter((f) => SEEDS[f]);
const newFiles = files.filter((f) => !SEEDS[f]);

const lines = [];
lines.push('// Prebuilt element catalog barrel (§13). AUTO-GENERATED by');
lines.push('// scripts/regen-element-barrel.mjs — do not hand-edit; re-run the script.');
lines.push('//');
lines.push('// Seeds use named export + explicit register; every other element self-');
lines.push('// registers on import (side-effect import). One import of this barrel');
lines.push('// registers the whole library — drawn from by the browser + AI authoring.');
lines.push('');
lines.push("import { registerElement } from '../registry';");
for (const f of seedFiles) lines.push(`import { ${SEEDS[f]} } from './${f}';`);
lines.push('');
lines.push('// Self-registering elements (side-effect imports):');
for (const f of newFiles) lines.push(`import './${f}';`);
lines.push('');
lines.push('let registered = false;');
lines.push('/** Idempotent: register the seed elements (the rest self-register on import). */');
lines.push('export function registerAllElements(): void {');
lines.push('  if (registered) return;');
for (const f of seedFiles) lines.push(`  registerElement(${SEEDS[f]});`);
lines.push('  registered = true;');
lines.push('}');
lines.push('');
lines.push('registerAllElements();');
lines.push('');
for (const f of seedFiles) lines.push(`export { ${SEEDS[f]} } from './${f}';`);
lines.push('');

writeFileSync(path.join(dir, 'index.ts'), lines.join('\n'));
console.log(`barrel regenerated: ${seedFiles.length} seeds + ${newFiles.length} self-registering = ${files.length} elements`);
console.log('new:', newFiles.join(', '));
